"""Generates the rebuild scaffold: a CMake C project prepared from the Ghidra analysis.

Workflow idea ("strangler" approach): every function of the binary gets its own source file
pre-filled with the decompiler output. The CMake project only compiles functions marked as
*done* in GhidraWorker, so the tree always builds and grows function by function.

Regeneration never destroys work: files the user edited (detected through a hash manifest)
are left untouched; only pristine generated files are refreshed.
"""

