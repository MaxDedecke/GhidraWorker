_IGNORED_DIRS = {"build", "out", ".git", ".vs", ".vscode", ".idea"}


def _iter_files(root: Path):
    """Source files of the rebuild tree (build output and IDE folders are skipped)."""
    if not root.exists():
        return
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        top = rel.parts[0]
        if top in _IGNORED_DIRS or top.startswith("cmake-build"):
            continue
        if p.is_file():
            yield p, rel.as_posix()


def tree(root: Path) -> list[dict]:
    return [
        {"path": rel, "size": p.stat().st_size}
        for p, rel in _iter_files(root)
        if p.name != MANIFEST
    ]


def safe_child(root: Path, rel: str) -> Path:
    path = (root / rel).resolve()
    root = root.resolve()
    if root not in path.parents:
        raise ValueError("invalid path")
    return path


def zip_dir(root: Path, prefix: str) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for p, rel in _iter_files(root):
            zf.write(p, f"{prefix}/{rel}")
    return buf.getvalue()
