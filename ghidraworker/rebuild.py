def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def c_ident(name: str) -> str:
    ident = _IDENT_RE.sub("_", name.replace("::", "__")).strip("_") or "fn"
    return ("_" + ident) if ident[0].isdigit() else ident


class _Writer:
    """Writes generated files while protecting files the user changed."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.manifest_path = root / MANIFEST
        try:
            self.manifest: dict = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            self.manifest = {}
        self.manifest.setdefault("files", {})
        self.manifest.setdefault("functions", {})
        self.kept: list[str] = []
        self.written: list[str] = []

    def user_modified(self, rel: str) -> bool:
        path = self.root / rel
        if not path.exists():
            return False
        known = self.manifest["files"].get(rel)
        try:
            current = _sha(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError):
            return True
        return known != current

    def write(self, rel: str, text: str, *, always: bool = False, once: bool = False) -> bool:
        """Write ``rel``.

        always: generated file, always overwritten (headers, cmake lists).
        once:   created only if missing (user owned afterwards).
        default: overwritten only while the user did not change it.
        """
        path = self.root / rel
        if path.exists():
            if once:
                return False
            if not always and self.user_modified(rel):
                self.kept.append(rel)
                return False
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        self.manifest["files"][rel] = _sha(text)
        self.written.append(rel)
        return True

    def remove_if_pristine(self, rel: str) -> bool:
        path = self.root / rel
        if path.exists() and not self.user_modified(rel):
            path.unlink()
            self.manifest["files"].pop(rel, None)
            return True
        return False

    def save(self) -> None:
        self.manifest["generated"] = now()
        self.manifest_path.write_text(json.dumps(self.manifest, indent=1), encoding="utf-8")


def _apply_renames(code: str, renames: dict[str, str]) -> str:
    if not renames:
        return code
    pattern = re.compile(r"\b(" + "|".join(re.escape(k) for k in sorted(renames, key=len, reverse=True)) + r")\b")
    return pattern.sub(lambda m: renames[m.group(1)], code)


def _sanitize_types(text: str) -> str:
    """Drop typedefs of Ghidra builtins that gw_ghidra.h provides in a portable way."""
    out = []
    builtin = re.compile(
        r"^typedef\s+[\w ]+\s+(undefined\d?|bool|byte|dword|qword|word|uchar|uint|ulong|"
        r"ulonglong|longlong|ushort|wchar_t|sbyte|float10|ImageBaseOffset32|ImageBaseOffset64)\s*;\s*$"
    )
    for line in text.splitlines():
        if builtin.match(line.strip()):
            out.append("/* " + line.strip() + "  -- provided by gw_ghidra.h */")
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def _library_name(dll: str) -> str:
    return dll.lower().removesuffix(".dll")


_ARRAY_RE = re.compile(r"^(.*?)((?:\[\d+\])+)$")
_C_WORDS = {"char", "short", "int", "long", "float", "double", "void", "signed", "unsigned",
            "struct", "union", "enum", "const", "volatile"}
_SKIP_BLOCKS = {"headers", ".pdata", ".xdata", ".reloc", ".idata", ".edata", ".rsrc", ".tls"}
MAX_GLOBAL_INIT = 1 << 20


def known_type_names(types_text: str) -> set[str]:
    """Names of all types defined in the exported C header (plus Ghidra builtins)."""
    names = set(re.findall(r"^typedef\s+[^;]*?\b(\w+)\s*(?:\(\))?;", GHIDRA_H, re.M))
    for line in types_text.splitlines():
        line = line.strip()
        m = re.match(r"^(?:struct|union|enum)\s+(\w+)\s*\{", line)
        if m:
            names.add(m.group(1))
            continue
        if not line.startswith("typedef"):
            continue
        fp = re.search(r"\(\s*\*?\s*(\w+)\s*\)\s*\(", line)
        if fp:
            names.add(fp.group(1))
            continue
        body = line.rstrip(";")
        body = re.sub(r"^typedef\s+(?:struct|union|enum)?\s*\w+\s*", "", body)
        for part in body.split(","):
            ids = re.findall(r"\w+", part)
            if ids:
                names.add(ids[-1])
    return names


def _global_decl(g: dict, name: str, known: set[str]) -> str:
    dtype = (g.get("dataType") or "undefined").strip()
    suffix = ""
    m = _ARRAY_RE.match(dtype)
    if m:
        dtype, suffix = m.group(1).strip(), m.group(2)
    words = re.findall(r"[A-Za-z_]\w*", dtype)
    valid = bool(words) and re.fullmatch(r"[\w\s]+\**", dtype) and all(
        w in known or w in _C_WORDS for w in words
    )
    if not valid:
        dtype, suffix = "undefined", f"[{g.get('length') or 1}]"
    return f"extern {dtype} {name}{suffix}; /* {g['address']} {g.get('block') or ''} {g.get('dataType') or ''} */"


def _select_globals(globals_: list[dict], sections: list[dict], taken: set[str]) -> list[tuple[dict, str]]:
    exec_blocks = {s["name"] for s in sections if s.get("execute")}
    out, used = [], set(taken)
    for g in globals_:
        block = g.get("block") or ""
        if block.lower() in _SKIP_BLOCKS or block in exec_blocks:
            continue
        name = c_ident(g["name"])
        if name in used:
            name = f"{name}_{c_ident(g['address'])}"
            if name in used:
                continue
        used.add(name)
        out.append((g, name))
    return out


def _data_file(selected: list[tuple[dict, str]], image, program: dict) -> str:
    lines = [
        "/*",
        " * Initial contents of the program's global data, copied byte by byte from the original",
        " * binary (generated by GhidraWorker – do not edit, put real definitions elsewhere).",
        " *",
        " * Absolute pointers inside this data still point into the ORIGINAL image; fix them up",
        " * when you rebuild code that relies on them (vtables, function pointer tables, ...).",
        " */",
        "#if defined(_MSC_VER)",
        "#define GW_ALIGN __declspec(align(8))",
        "#else",
        "#define GW_ALIGN __attribute__((aligned(8)))",
        "#endif",
        "",
    ]
    try:
        ghidra_base = int(program.get("imageBase") or "0", 16)
    except ValueError:
        ghidra_base = 0
    for g, name in selected:
        length = max(1, int(g.get("length") or 1))
        raw = None
        if image is not None and length <= MAX_GLOBAL_INIT:
            try:
                va = int(g["address"], 16) - ghidra_base + image.image_base
                raw = image.read(va, length)
            except ValueError:
                raw = None
        comment = f"/* {g['address']} {g.get('block') or ''} {g.get('dataType') or ''} */"
        if raw is None or not any(raw):
            lines.append(f"GW_ALIGN unsigned char {name}[{length}]; {comment}")
            continue
        lines.append(f"GW_ALIGN unsigned char {name}[{length}] = {{ {comment}")
        for i in range(0, length, 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in raw[i : i + 16]) + ",")
        lines.append("};")
    lines.append("")
    return "\n".join(lines)


def generate(store: ProjectStore, pid: str) -> dict:
    meta = store.get(pid)
    root = store.rebuild_dir(pid)
    root.mkdir(parents=True, exist_ok=True)
    adir = store.analysis_dir(pid)
    w = _Writer(root)

    program = store.analysis(pid, "program", {}) or {}
    funcs = store.functions(pid)
    imports = store.analysis(pid, "imports", []) or []
    globals_ = store.analysis(pid, "globals", []) or []
    pe = (meta.get("binary") or {}).get("pe") or {}
    by_addr = {f["address"]: f for f in funcs}

    # rename map: old Ghidra name -> name chosen in GhidraWorker
    renames = {f["name"]: c_ident(f["newName"]) for f in funcs if f.get("newName") and f["newName"] != f["name"]}

    # ---------------------------------------------------------------- headers
    w.write("include/gw_ghidra.h", GHIDRA_H, always=True)
    w.write("include/gw_rebuild.h", REBUILD_H, always=True)
    try:
        types = (adir / "types.h").read_text(encoding="utf-8", errors="replace")
    except OSError:
        types = "/* no type information exported */\n"
    w.write(
        "include/gw_types.h",
        "#ifndef GW_TYPES_H\n#define GW_TYPES_H\n#include \"gw_ghidra.h\"\n\n"
        + _sanitize_types(types)
        + "\n#endif /* GW_TYPES_H */\n",
        always=True,
    )

    libs: dict[str, list[dict]] = {}
    for imp in imports:
        libs.setdefault(imp.get("library") or "?", []).append(imp)
    lines = [
        "/* Imported functions (generated by GhidraWorker). */",
        "#ifndef GW_IMPORTS_H",
        "#define GW_IMPORTS_H",
        "",
        "/* Set GW_USE_SYSTEM_HEADERS to use the real SDK headers instead of these declarations. */",
        "#ifdef GW_USE_SYSTEM_HEADERS",
        "#include <windows.h>" if pe else "/* add the platform headers here */",
        "#else",
    ]
    for lib in sorted(libs):
        lines.append(f"\n/* ---- {lib} ---- */")
        for imp in sorted(libs[lib], key=lambda i: i.get("name") or ""):
            sig = imp.get("signature")
            if sig and "(" in sig:
                lines.append(f"{sig};")
            else:
                lines.append(f"/* {imp.get('name')}: signature unknown */")
    lines += ["#endif", "", "#endif /* GW_IMPORTS_H */", ""]
    w.write("include/gw_imports.h", "\n".join(lines), always=True)

    sections = store.analysis(pid, "sections", []) or []
    taken = {c_ident(f["displayName"]) for f in funcs} | {c_ident(f["name"]) for f in funcs}
    taken |= {c_ident(i.get("name") or "") for i in imports}
    selected = _select_globals(globals_, sections, taken)
    known = known_type_names(types)
    gl = ["/* Global data referenced by the program (generated by GhidraWorker).",
          " * Definitions with the original initial values: src/gw_data.c */",
          "#ifndef GW_GLOBALS_H", "#define GW_GLOBALS_H", ""]
    gl += [_global_decl(g, name, known) for g, name in selected]
    gl += ["", "#endif /* GW_GLOBALS_H */", ""]
    w.write("include/gw_globals.h", "\n".join(gl), always=True)

    image = None
    if pe:
        try:
            image = PEImage(store.binary_path(pid))
        except (OSError, ValueError, struct.error):
            image = None
    w.write("src/gw_data.c", _data_file(selected, image, program), always=True)

    # ---------------------------------------------------------------- functions
    relevant = [f for f in funcs if f["status"] != "skip"]
    proto = ["/* Prototypes of all functions to rebuild (generated by GhidraWorker). */",
             "#ifndef GW_FUNCTIONS_H", "#define GW_FUNCTIONS_H", ""]
    for f in relevant:
        sig = (f.get("cSignature") or f["signature"]).strip().rstrip(";")
        proto.append(f"{sig}; /* {f['address']} */")
    proto += ["", "#endif /* GW_FUNCTIONS_H */", ""]
    w.write("include/gw_functions.h", _apply_renames("\n".join(proto), renames), always=True)

    sources: list[str] = []
    seen_addrs = set()
    for f in relevant:
        addr = f["address"]
        seen_addrs.add(addr)
        rel = f"src/functions/{f['file']}_{c_ident(f['displayName'])}.c"
        prev = w.manifest["functions"].get(addr)
        if prev and prev != rel:
            if (root / prev).exists() and w.user_modified(prev):
                rel = prev  # user works in the old file -> keep using it
            else:
                w.remove_if_pristine(prev)
        try:
            code = (adir / "decompiled" / f"{f['file']}.c").read_text(encoding="utf-8", errors="replace")
        except OSError:
            code = "/* no decompiler output */\n"
        w.write(rel, _function_file(f, code, by_addr, renames))
        w.manifest["functions"][addr] = rel
        if f["status"] == "done":
            sources.append(rel)

    # functions that disappeared or got skipped -> drop pristine files
    for addr in list(w.manifest["functions"]):
        if addr not in seen_addrs:
            rel = w.manifest["functions"].pop(addr)
            w.remove_if_pristine(rel)

    cm = ["# Sources of functions marked as done (generated by GhidraWorker – do not edit).",
          "set(GW_SOURCES"]
    cm.append("  ${CMAKE_CURRENT_LIST_DIR}/../src/gw_data.c")
    cm += [f"  ${{CMAKE_CURRENT_LIST_DIR}}/../{s}" for s in sorted(sources)]
    cm += [")", ""]
    w.write("cmake/gw_sources.cmake", "\n".join(cm), always=True)

    link_libs = sorted({_library_name(l) for l in libs if l and l != "?"} - _CRT_LIBS)
    link_libs = [l for l in link_libs if not l.startswith("api-ms-win-")]
    cl = ["# Import libraries of the original binary (generated by GhidraWorker).",
          "set(GW_LIBRARIES " + " ".join(link_libs) + ")", ""]
    w.write("cmake/gw_libraries.cmake", "\n".join(cl), always=True)

    # ---------------------------------------------------------------- once-only files
    name = c_ident(Path(meta["binary"]["filename"]).stem) or "rebuild"
    win32 = " WIN32" if pe.get("subsystem") == "windows" else ""
    w.write(
        "CMakeLists.txt",
        CMAKELISTS.format(binary=meta["binary"]["filename"], project=name, target=name, win32=win32),
        once=True,
    )
    entries = program.get("entryPoints") or []
    entry_lines = "\n".join(f" *   {e['address']}  {e.get('name') or ''}" for e in entries) or " *   (keine)"
    w.write("src/main.c", MAIN_C.format(entries=entry_lines, name=name), once=True)
    w.write(".gitignore", "build/\n", once=True)

    # ---------------------------------------------------------------- plan
    w.write("PLAN.md", _plan(meta, program, pe, funcs, relevant, libs, sources, w.kept), always=True)
    w.save()
    return {
        "written": len(w.written),
        "kept": w.kept,
        "sources": len(sources),
        "functions": len(relevant),
    }


def _function_file(f: dict, code: str, by_addr: dict, renames: dict[str, str]) -> str:
    def names(addrs):
        return ", ".join(by_addr[a]["displayName"] if a in by_addr else a for a in addrs[:20]) + (
            f" … (+{len(addrs) - 20})" if len(addrs) > 20 else ""
        )

    header = [
        "/*",
        f" * {f['displayName']}",
        f" *   Adresse:  {f['address']}   Größe: {f['size']} Bytes   Original-Name: {f['name']}",
        f" *   Ghidra:   {f['signature']}",
    ]
    if f.get("callers"):
        header.append(f" *   Aufrufer: {names(f['callers'])}")
    if f.get("callees"):
        header.append(f" *   Ruft auf: {names(f['callees'])}")
    if f.get("externalCalls"):
        header.append(f" *   Imports:  {', '.join(f['externalCalls'][:20])}")
    if f.get("notes"):
        header.append(" *")
        header += [f" *   {line}" for line in f["notes"].replace("*/", "* /").splitlines()]
    header += [
        " *",
        " * Vom Ghidra-Decompiler erzeugt. Bereinigen, testen und in GhidraWorker auf",
        " * \"fertig\" setzen – dann wird die Datei in den Build aufgenommen.",
        " */",
        '#include "gw_rebuild.h"',
        "",
    ]
    return "\n".join(header) + _apply_renames(code.strip("\n"), renames) + "\n"


def _plan(meta, program, pe, funcs, relevant, libs, sources, kept) -> str:
    counts = {s: 0 for s in ("todo", "progress", "done", "skip")}
